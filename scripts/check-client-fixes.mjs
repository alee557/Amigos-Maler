import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { validConsultationPreference, swissToday } from '../src/lib/workDates.js';
import { validatePropertyDetails, filterProperties } from '../src/lib/propertyDetails.js';
import { requestDetails } from '../src/lib/requestFields.js';
import { translateMessage } from '../src/lib/i18n.js';

const tomorrow = new Date(Date.parse(swissToday()+'T12:00:00Z')+86400000).toISOString().slice(0,10);
assert(validConsultationPreference('', ''));
assert(validConsultationPreference(tomorrow, '14:30'));
for (const [day,time] of [[tomorrow,''],['','12:00'],['2020-01-01','12:00'],['2099-02-30','12:00'],[tomorrow,'24:30'],[tomorrow,'12:99'],[tomorrow,{}]]) assert.equal(validConsultationPreference(day,time),false);
assert.equal(validatePropertyDetails({amount:-1}),null);
assert.equal(validatePropertyDetails({amount:'Infinity'}),null);
assert.equal(validatePropertyDetails({gallery:'javascript:alert(1)'}),null);
assert.equal(validatePropertyDetails({documents:'https://user:password@example.com/private.pdf'}),null);
assert.equal(validatePropertyDetails({gallery:[]}),null);
const extra=validatePropertyDetails({propertyType:'House',amount:'1200',gallery:'https://example.com/photo.jpg',description:'Approved description'});
assert.equal(extra.amount,1200);
assert.equal(extra.gallery.length,1);
const rows=[{id:'1',type:'rent',location:'Olten',extra},{id:'2',type:'sale',location:'Aarau',extra:{currency:'CHF',amount:1500,propertyType:'Apartment'}}];
assert.deepEqual(filterProperties(rows,{offer:'rent',location:'OLTEN',maxPrice:'1300'}).map(r=>r.id),['1']);
assert.equal(filterProperties(rows,{propertyType:'Land'}).length,0);
assert.equal(filterProperties([{type:'rent',location:'Olten',price:'On request'}],{maxPrice:'1200'}).length,0);
const form=new FormData(); for(const [k,v] of Object.entries({company:'Test',trade:'Painting',region:'Olten',address:'Example 1'}))form.set(k,v);
assert.equal(requestDetails('Partner application',form),null);
form.set('consent','on'); assert(requestDetails('Partner application',form).length>=5);
form.set('website','javascript:alert(1)'); assert.equal(requestDetails('Partner application',form),null);
for(const locale of ['de','es']) for(const key of ['Download preview','View property','Preferred consultation time','Business address']) assert.notEqual(translateMessage(key,locale),key);
for(const asset of ['room.webp','masks/front-wall.webp','masks/left-wall.webp','masks/right-wall.webp']) assert(existsSync(new URL(`../public/assets/${asset}`,import.meta.url)));
console.log('Client fixes: date/time validation, safe publication fields, filters, consent and new translations passed.');
